#include <stdio.h>

// ==========================================
// โปรแกรมหลัก (ถามจำนวนไบต์ รับค่าทีละชุด และคำนวณ Checksum)
// ==========================================
int main() {
    int count;                                              // ตัวแปรเก็บจำนวนไบต์ที่ต้องการคำนวณ
    printf("How many bytes: ");
    scanf("%d", &count);                                    // รับจำนวนไบต์จากคีย์บอร์ด

    if (count <= 0) {
        printf("Invalid count.\n");                         // แจ้งเตือนหากใส่จำนวนน้อยกว่าหรือเท่ากับ 0
        return 1;
    }

    unsigned int sum = 0;                                   // ตัวแปรเก็บผลรวมทั้งหมด
    char buffer[16];                                        // พื้นที่พักข้อความเลขฐาน 2 ที่รับเข้ามา

    // ------------------------------------------
    // 1. วนลูปรับเลขฐาน 2 ทีละชุดและบวกรวมทันที
    // ------------------------------------------
    for (int i = 0; i < count; i++) {
        printf("8-bit binary: ");
        scanf("%15s", buffer);                              // รับข้อความเลขฐาน 2 เก็บลง buffer

        unsigned char value = 0;                            // ตัวแปรพักค่าเลขฐาน 10 ของชุดนี้
        for (char *p = buffer; *p != '\0'; p++) {           // ใช้ Pointer เลื่อนอ่านทีละตัวอักษร
            if (*p < '0' || *p > '1') break;                // หยุดแปลงหากเจอตัวอักษรอื่นที่ไม่ใช่ 0 หรือ 1
            value = (value << 1) + (*p - '0');              // เลื่อนบิตซ้าย 1 ตำแหน่ง แล้วบวกบิตปัจจุบัน
        }
        sum += value;                                       // บวกเข้าผลรวมทันที
    }

    // ------------------------------------------
    // 2. คำนวณ Wrap-around และ 1's Complement
    // ------------------------------------------
    while (sum > 0xFF) {
        sum = (sum & 0xFF) + (sum >> 8);                    // ทบบิตที่ล้นเกิน 8 บิตกลับมาบวก
    }
    unsigned char checksum = ~sum;                          // กลับบิตทั้งหมด (1's Complement) เหลือ 8 บิตล่าง

    // ------------------------------------------
    // 3. แสดงผลลัพธ์ (Binary และ Hex)
    // ------------------------------------------
    printf("Checksum (Bin): ");
    for (int i = 7; i >= 0; i--) {
        printf("%d", (checksum >> i) & 1);                  // ดึงค่าทีละบิตจากซ้ายไปขวาเพื่อแสดงผล
    }
    printf("\nChecksum (Hex): 0x%02X\n", checksum);         // แสดงผลในรูปแบบเลขฐาน 16

    return 0;
}
