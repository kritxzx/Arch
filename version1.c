#include <stdio.h>

// ==========================================
// โปรแกรมหลัก (รับค่า คำนวณ Checksum และแสดงผล)
// ==========================================
int main(int argc, char *argv[]) {
    if (argc < 2) {
        printf("Usage: %s <bin1> <bin2> ...\n", argv[0]);     // แจ้งวิธีใช้งานหากส่งพารามิเตอร์ไม่ครบ
        return 1;
    }

    unsigned int sum = 0;                                   // ตัวแปรเก็บผลรวมทั้งหมด (ไม่ต้องสร้างอาเรย์พักข้อมูล)

    // ------------------------------------------
    // 1. วนลูปแปลงเลขฐาน 2 และบวกรวมทันที
    // ------------------------------------------
    for (int i = 1; i < argc; i++) {
        unsigned char value = 0;                            // ตัวแปรพักค่าของข้อมูลแต่ละชุด
        for (char *p = argv[i]; *p != '\0'; p++) {          // ใช้ Pointer เลื่อนอ่านทีละตัวอักษรจนจบข้อความ
            value = (value << 1) + (*p - '0');              // เลื่อนบิตซ้าย 1 ตำแหน่ง แล้วบวกบิตปัจจุบัน (0 หรือ 1)
        }
        sum += value;                                       // บวกเข้าผลรวมทันที ลดการใช้หน่วยความจำอาเรย์
    }

    // ------------------------------------------
    // 2. คำนวณ Wrap-around และ 1's Complement
    // ------------------------------------------
    while (sum > 0xFF) {
        sum = (sum & 0xFF) + (sum >> 8);                    // ทบบิตที่ล้นเกิน 8 บิตกลับมาบวก
    }
    unsigned char checksum = ~sum;                          // กลับบิตทั้งหมด (1's Complement) เหลือ 8 บิตล่าง

    // ------------------------------------------
    // 3. แสดงผลลัพธ์ (Binary และ Hex)
    // ------------------------------------------
    printf("Checksum (Bin): ");
    for (int i = 7; i >= 0; i--) {
        printf("%d", (checksum >> i) & 1);                  // ดึงค่าทีละบิตจากซ้ายไปขวาเพื่อแสดงผล
    }
    printf("\nChecksum (Hex): 0x%02X\n", checksum);         // แสดงผลในรูปแบบเลขฐาน 16

    return 0;
}